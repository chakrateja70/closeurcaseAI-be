def load_dataset_csv(path: Path) -> list[dict[str, str]]:
    """Load the existing Closeurcase evaluation CSV."""

    if not path.exists():
        raise FileNotFoundError(f"Dataset not found: {path}")

    with path.open("r", encoding="utf-8-sig", newline="") as file:
        rows = list(csv.DictReader(file))

    required_columns = {
        "id",
        "category",
        "difficulty",
        "question",
        "ground_truth_answer",
    }

    if not rows:
        raise ValueError("Evaluation CSV is empty.")

    missing = required_columns - set(rows[0].keys())

    if missing:
        raise ValueError(
            f"Dataset is missing required columns: {sorted(missing)}"
        )

    return rows


async def evaluate_question(
    row: dict[str, str],
    case_id: str,
    top_k: int,
) -> dict[str, Any]:
    """
    Run production retrieval + production answer generation.

    Important:
    search_chunks() is called here to capture the exact contexts that RAGAS
    will evaluate. answer_query() then runs the production answer path.
    """

    question = row["question"]

    retrieval_start = time.perf_counter()

    try:
        retrieved_chunks = await search_chunks(
            question,
            case_id=case_id,
            top_k=top_k,
        )
    except Exception as exc:
        return {
            "id": row["id"],
            "category": row["category"],
            "difficulty": row["difficulty"],
            "question": question,
            "ground_truth": row["ground_truth_answer"],
            "answer": "",
            "contexts": [],
            "retrieval_latency_ms": round(
                (time.perf_counter() - retrieval_start) * 1000, 2
            ),
            "generation_latency_ms": 0.0,
            "total_latency_ms": round(
                (time.perf_counter() - retrieval_start) * 1000, 2
            ),
            "error": f"retrieval_error: {type(exc).__name__}: {exc}",
        }

    retrieval_latency = time.perf_counter() - retrieval_start

    # Keep exactly the text returned by production retrieval.
    contexts = [
        str(chunk.get("text") or "").strip()
        for chunk in retrieved_chunks
        if str(chunk.get("text") or "").strip()
    ]

    generation_start = time.perf_counter()

    try:
        result = await answer_query(
            case_id,
            question,
        )
    except Exception as exc:
        return {
            "id": row["id"],
            "category": row["category"],
            "difficulty": row["difficulty"],
            "question": question,
            "ground_truth": row["ground_truth_answer"],
            "answer": "",
            "contexts": contexts,
            "retrieval_latency_ms": round(retrieval_latency * 1000, 2),
            "generation_latency_ms": round(
                (time.perf_counter() - generation_start) * 1000, 2
            ),
            "total_latency_ms": round(
                (time.perf_counter() - retrieval_start) * 1000, 2
            ),
            "error": f"generation_error: {type(exc).__name__}: {exc}",
        }

    generation_latency = time.perf_counter() - generation_start
    total_latency = time.perf_counter() - retrieval_start

    return {
        "id": row["id"],
        "category": row["category"],
        "difficulty": row["difficulty"],
        "question": question,
        "ground_truth": row["ground_truth_answer"],
        "answer": str(result.get("answer") or ""),
        "contexts": contexts,
        "sources": result.get("sources", []),
        "retrieved_count": len(contexts),
        "retrieval_latency_ms": round(retrieval_latency * 1000, 2),
        "generation_latency_ms": round(generation_latency * 1000, 2),
        "total_latency_ms": round(total_latency * 1000, 2),
        "error": "",
    }


async def collect_results(
    rows: list[dict[str, str]],
    case_id: str,
    top_k: int,
) -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []

    print()
    print("=" * 70)
    print("CLOSEURCASE RAGAS DATA COLLECTION")
    print("=" * 70)
    print(f"Questions : {len(rows)}")
    print(f"Case ID   : {case_id}")
    print(f"Top-K     : {top_k}")
    print()

    for index, row in enumerate(rows, start=1):
        print(
            f"[{index:02d}/{len(rows):02d}] "
            f"{row['id']} - {row['question'][:80]}"
        )

        result = await evaluate_question(
            row=row,
            case_id=case_id,
            top_k=top_k,
        )

        results.append(result)

        if result["error"]:
            print(f"       ERROR: {result['error']}")
        else:
            print(
                f"       retrieval={result['retrieval_latency_ms']:.0f}ms | "
                f"generation={result['generation_latency_ms']:.0f}ms | "
                f"total={result['total_latency_ms']:.0f}ms | "
                f"contexts={result['retrieved_count']}"
            )

    return results


def build_ragas_dataset(results: list[dict[str, Any]]) -> Dataset:
    """
    Build the standard RAGAS dataset supporting both current (v0.4+) and legacy schemas.
    """

    rows = []

    for result in results:
        rows.append(
            {
                # Modern Ragas keys
                "user_input": result["question"],
                "response": result["answer"],
                "retrieved_contexts": result["contexts"],
                "reference": result["ground_truth"],
                # Legacy keys
                "question": result["question"],
                "answer": result["answer"],
                "contexts": result["contexts"],
                "ground_truth": result["ground_truth"],
            }
        )

    return Dataset.from_list(rows)


def save_collection(
    results: list[dict[str, Any]],
    output_dir: Path,
) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = output_dir / f"ragas_input_{timestamp}.json"

    with path.open("w", encoding="utf-8") as file:
        json.dump(results, file, indent=2, ensure_ascii=False)

    return path


def save_ragas_scores(
    scores: Any,
    output_dir: Path,
) -> tuple[Path, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    json_path = output_dir / f"ragas_summary_{timestamp}.json"
    csv_path = output_dir / f"ragas_results_{timestamp}.csv"

    # RAGAS EvaluationResult can be converted to a pandas DataFrame.
    dataframe = scores.to_pandas()

    dataframe.to_csv(
        csv_path,
        index=False,
        encoding="utf-8-sig",
    )

    summary = {
        "faithfulness": None,
        "answer_relevancy": None,
        "answer_correctness": None,
        "context_precision": None,
        "context_recall": None,
        "questions": len(dataframe),
    }

    for metric in summary:
        if metric == "questions":
            continue

        if metric in dataframe.columns:
            values = dataframe[metric].dropna()

            if len(values):
                summary[metric] = float(values.mean())

    with json_path.open("w", encoding="utf-8") as file:
        json.dump(summary, file, indent=2)

    return csv_path, json_path


def print_summary(
    results: list[dict[str, Any]],
    scores: Any,
) -> None:
    dataframe = scores.to_pandas()

    print()
    print("=" * 70)
    print("CLOSEURCASE RAGAS EVALUATION")
    print("=" * 70)

    print()
    print("Dataset")
    print("-" * 70)
    print(f"Questions              : {len(dataframe)}")
    print(
        f"Successful             : "
        f"{sum(not result['error'] for result in results)}"
    )
    print(
        f"Errors                 : "
        f"{sum(bool(result['error']) for result in results)}"
    )

    print()
    print("RAGAS SCORES")
    print("-" * 70)

    metric_names = [
        ("faithfulness", "Faithfulness"),
        ("answer_relevancy", "Answer Relevancy"),
        ("answer_correctness", "Answer Correctness"),
        ("context_precision", "Context Precision"),
        ("context_recall", "Context Recall"),
    ]

    for column, label in metric_names:
        if column in dataframe.columns:
            values = dataframe[column].dropna()

            if len(values):
                score = float(values.mean())
                print(f"{label:<24}: {score:.4f} ({score * 100:.2f}%)")
            else:
                print(f"{label:<24}: N/A")
        else:
            print(f"{label:<24}: N/A")

    valid = [r for r in results if not r["error"]]

    if valid:
        avg_retrieval = sum(
            r["retrieval_latency_ms"] for r in valid
        ) / len(valid)

        avg_generation = sum(
            r["generation_latency_ms"] for r in valid
        ) / len(valid)

        avg_total = sum(
            r["total_latency_ms"] for r in valid
        ) / len(valid)

        print()
        print("Latency")
        print("-" * 70)
        print(f"Retrieval avg           : {avg_retrieval:.2f} ms")
        print(f"Generation avg         : {avg_generation:.2f} ms")
        print(f"End-to-end avg         : {avg_total:.2f} ms")


async def run(args: argparse.Namespace) -> None:
    if args.from_file:
        input_path = Path(args.from_file)
        if not input_path.exists():
            raise FileNotFoundError(f"Input file not found: {input_path}")
        with input_path.open("r", encoding="utf-8") as file:
            results = json.load(file)
        collection_file = input_path
        print()
        print(f"Loaded {len(results)} collected questions from {input_path}")
    else:
        rows = load_dataset_csv(Path(args.dataset))

        results = await collect_results(
            rows=rows,
            case_id=args.case_id,
            top_k=args.top_k,
        )

        collection_file = save_collection(
            results,
            Path(args.output_dir),
        )

    errors = [r for r in results if r.get("error")]

    if errors:
        print()
        print(
            f"WARNING: {len(errors)} question(s) failed. "
            "They will be excluded from RAGAS scoring."
        )

    valid_results = [r for r in results if not r.get("error")]

    if not valid_results:
        raise RuntimeError("No successful results available for RAGAS evaluation.")

    print()
    print("Running RAGAS evaluation...")
    print("This evaluates the generated answers against the retrieved contexts")
    print("and the ground-truth answers.")
    print()

    ragas_dataset = build_ragas_dataset(valid_results)

    # Use modern ragas factories — no Langchain wrappers needed.
    from openai import AsyncOpenAI
    _client = AsyncOpenAI(timeout=300, max_retries=5)
    _llm = llm_factory(model="gpt-4o-mini", client=_client)
    # Legacy metrics call embed_query/embed_documents, which the modern embeddings lack.
    from langchain_openai import OpenAIEmbeddings
    from ragas.embeddings import LangchainEmbeddingsWrapper

    _emb = LangchainEmbeddingsWrapper(OpenAIEmbeddings(model="text-embedding-3-small"))

    metrics = [
        faithfulness,
        answer_relevancy,
        answer_correctness,
        context_precision,
        context_recall,
    ]
    for metric in metrics:
        metric.llm = _llm
        if hasattr(metric, "embeddings"):
            metric.embeddings = _emb

    scores = evaluate(
        ragas_dataset,
        metrics=metrics,
        run_config=RunConfig(timeout=300, max_workers=4, max_retries=5),
    )

    results_csv, summary_json = save_ragas_scores(
        scores=scores,
        output_dir=Path(args.output_dir),
    )

    print_summary(
        results=results,
        scores=scores,
    )

    print()
    print("=" * 70)
    print(f"RAGAS detailed results : {results_csv}")
    print(f"RAGAS summary          : {summary_json}")
    print(f"Collected input        : {collection_file}")
    print("=" * 70)


