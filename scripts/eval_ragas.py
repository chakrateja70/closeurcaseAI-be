"""
RAGAS evaluation for Closeurcase case Q&A.

Runs the SAME production retrieval and answer generation used by Closeurcase,
then evaluates the resulting dataset with RAGAS.

Usage:
    python scripts/ragas_eval.py

Optional:
    python scripts/ragas_eval.py --case-id string
    python scripts/ragas_eval.py --dataset scripts/valluru_feroz_ahamad_rag_eval_dataset.csv
    python scripts/ragas_eval.py --top-k 10

Install once:
    pip install ragas datasets

Notes:
- No page_number is used.
- Retrieved contexts come directly from your production search_chunks().
- Answers come directly from your production answer_query().
- RAGAS evaluates:
    faithfulness
    answer_relevancy
    answer_correctness
    context_precision
    context_recall
- Because answer_query() performs its own retrieval, this script performs one
  extra search_chunks() call only to capture contexts for RAGAS. The answer
  itself is still generated by your production answer_query().
"""

